// Пакет main реализует multichecker — единый бинарник, объединяющий
// несколько независимых статических анализаторов и запускающий их за
// один проход по исходному коду на Go.
//
// # Сборка
//
// Из корня репозитория:
//
//	go build -o bin/staticlint ./cmd/staticlint
//
// # Запуск
//
// Бинарник следует тем же соглашениям командной строки, что и `go vet`.
// В качестве аргументов передаются один или несколько шаблонов пакетов:
//
//	./bin/staticlint ./...
//	./bin/staticlint ./internal/handler/...
//
// Чтобы вывести список всех анализаторов с их флагами:
//
//	./bin/staticlint -help
//
// Чтобы включить или отключить отдельный анализатор, используется флаг
// с именем этого анализатора, например:
//
//	./bin/staticlint -printf=false ./...
//	./bin/staticlint -SA1000 ./...
package main
